export function t(message: string, locale: MobileLocale = mobileLocale()): string {
  return locale === "zh-CN" ? (zhCN[message] ?? message) : message;
}

export function formatMobile(
  message: string,
  values: Record<string, string | number>,
  locale: MobileLocale = mobileLocale(),
): string {
  return t(message, locale).replace(/\{(\w+)\}/g, (match, key: string) =>
    String(values[key] ?? match),
  );
}
